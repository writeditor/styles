// 1. Inlines every .css under src/ into src/css.generated.ts (the browser and Node cannot import .css as text the same way).
// 2. Writes one self-contained stylesheet and one JSON (page + fields) per style to dist/: what you ship.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const src = new URL("../src/", import.meta.url), css: Record<string, string> = {};
for (const f of readdirSync(src, { recursive: true, encoding: "utf8" }).sort()) if (f.endsWith(".css")) css[f.replace(/\.css$/, "")] = readFileSync(new URL(f, src), "utf8");
writeFileSync(new URL("css.generated.ts", src), `// Generated by scripts/build.ts from the .css files; edit those.\nexport const CSS: Record<string, string> = ${JSON.stringify(css, null, 2)};\n`);

const { STYLES } = await import("../src/index.ts");
mkdirSync(new URL("../dist/", import.meta.url), { recursive: true });
for (const { css: page, editor, ...meta } of Object.values(STYLES)) {
  writeFileSync(new URL(`../dist/${meta.id}.css`, import.meta.url), `/* ${meta.id}: generated by scripts/build.ts from src/base.css + src/${meta.id}/style.css */\n${css.base}\n${page}`);
  writeFileSync(new URL(`../dist/${meta.id}.json`, import.meta.url), JSON.stringify(meta, null, 2) + "\n");
}
